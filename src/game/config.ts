/** 진짜 공주님. 이 이름을 입력했을 때만 극진히 환대함. */
export const PRINCESS = '최효은'

/** 이름 비교용 정규화 (공백 제거) */
export function isPrincess(name: string) {
  return name.replace(/\s/g, '') === PRINCESS
}

